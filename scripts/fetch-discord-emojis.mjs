// Downloads the PictureGame Discord server's custom emojis for emoji masks and stamps.
//
//   node fetch-discord-emojis.mjs <bot-config.json> <output-dir>
//
// Run it where the Discord bot's config lives (it reads discord.auth.token and discord.serverId;
// the token is only sent to Discord). It writes <output-dir>/images/discord-emojis/<id>.png (the
// first frame of animated ones) and <output-dir>/src/masks/discordEmojis.js;
// copy both into the repo. Needs Node 18+ (fetch).

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const [configPath, outDir] = process.argv.slice(2);

if (!configPath || !outDir) {
  console.error('Usage: node fetch-discord-emojis.mjs <bot-config.json> <output-dir>');
  process.exit(1);
}

const config = JSON.parse(await readFile(configPath, 'utf8'));
const token = config.discord?.auth?.token;
const guild = config.discord?.serverId;

if (!token || !/^\d+$/.test(String(guild))) {
  throw new Error('The config has no discord.auth.token or discord.serverId.');
}

const response = await fetch(`https://discord.com/api/v10/guilds/${guild}/emojis`, { headers: { Authorization: `Bot ${token}` } });

if (!response.ok) {
  throw new Error(`Discord answered ${response.status}`);
}

const emojis = (await response.json()).filter((emoji) => emoji.available !== false && /^\d+$/.test(emoji.id) && /^[\w~-]{2,32}$/.test(emoji.name));
const imageDir = join(outDir, 'images', 'discord-emojis');

await mkdir(imageDir, { recursive: true });
await mkdir(join(outDir, 'src', 'masks'), { recursive: true });

const list = [];

for (const emoji of emojis.sort((a, b) => a.name.localeCompare(b.name))) {
  // Animated ones are kept as their first frame: masks and stamps are still pictures.
  const image = await fetch(`https://cdn.discordapp.com/emojis/${emoji.id}.png?size=128`);

  if (!image.ok) {
    console.warn(`skipped ${emoji.name}: ${image.status}`);
    continue;
  }

  await writeFile(join(imageDir, `${emoji.id}.png`), Buffer.from(await image.arrayBuffer()));
  list.push({ name: emoji.name, id: emoji.id });
}

const body = list.map((emoji) => `  { name: '${emoji.name}', id: '${emoji.id}' },`).join('\n');

await writeFile(
  join(outDir, 'src', 'masks', 'discordEmojis.js'),
  `// The PictureGame Discord server's custom emojis (images/discord-emojis/<id>.png).
// Generated by scripts/fetch-discord-emojis.mjs; run it again to update.

export const DISCORD_EMOJIS = [
${body}
];
`
);

console.log(`${list.length} emojis`);
