// Rewrites the <link rel="modulepreload"> block in index.html from the modules src/main.js loads
// up front (static imports, followed recursively; dynamic import() stays lazy on purpose).
//
// Without it the browser only finds each module after the one importing it has arrived, so the
// first visit waits for one round trip per level of imports. With every module listed in the
// page, they are all requested at once.
//
//   node scripts/update-preloads.mjs          rewrites index.html
//   node scripts/update-preloads.mjs --check  exits 1 if index.html is out of date
//
// dev/tests.html runs the same check in the browser.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, posix, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const START = '<!-- modulepreload: generated by scripts/update-preloads.mjs -->';
const END = '<!-- /modulepreload -->';

/** Static import / export-from specifiers of a module's source. */
export function staticImports(source) {
  const code = source.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');
  const found = [];
  const pattern = /(?:^|[;\n])\s*(?:import|export)\s+(?:[^'"`;]*?\s+from\s+)?['"]([^'"]+)['"]/g;

  for (const match of code.matchAll(pattern)) {
    found.push(match[1]);
  }

  return found;
}

function graph(entry) {
  const seen = new Set();
  const visit = (file) => {
    if (seen.has(file)) {
      return;
    }

    seen.add(file);

    for (const specifier of staticImports(readFileSync(join(root, file), 'utf8'))) {
      if (specifier.startsWith('.') && specifier.endsWith('.js')) {
        visit(posix.normalize(posix.join(posix.dirname(file), specifier)));
      }
    }
  };

  visit(entry);
  return [...seen].sort();
}

const modules = graph('src/main.js');
const indexPath = join(root, 'index.html');
const html = readFileSync(indexPath, 'utf8');
// Keep the file's own line endings (a Windows checkout may have CRLF).
const newline = html.includes('\r\n') ? '\r\n' : '\n';
const block = [START, ...modules.map((file) => `  <link rel="modulepreload" href="${file}">`), `  ${END}`].join(newline);
const start = html.indexOf(START);
const end = html.indexOf(END);

if (start === -1 || end === -1) {
  console.error(`index.html needs the markers ${START} and ${END}`);
  process.exit(1);
}

const next = `${html.slice(0, start)}${block}${html.slice(end + END.length)}`;

if (process.argv.includes('--check')) {
  if (next !== html) {
    console.error('index.html preloads are out of date: run node scripts/update-preloads.mjs');
    process.exit(1);
  }

  console.log(`${modules.length} modules, index.html is up to date`);
} else {
  writeFileSync(indexPath, next);
  console.log(`${modules.length} modules preloaded (${relative(root, indexPath)})`);
}
